// Builds src/content/legal.generated.ts from pravni/archiv/<doc>/<version>.html.
// Workflow for a new version: edit pravni/<doc>.md → render HTML (pravni-dokumenty-cz skill: md2html.py
// pravni/ --out pravni/html --toc) → copy pravni/html/<doc>.html to pravni/archiv/<doc>/<new>.html →
// add it to DOCS below → `npm run legal:build`. Old versions stay published in the archive.
import { readFileSync, writeFileSync } from "node:fs";

const DOCS = {
  podminky: { file: "podminky-uzivani", title: "Podmínky užívání", versions: [{ v: "1.0", from: "2026-11-27" }, { v: "1.1", from: "2026-11-27" }] },
  soukromi: { file: "zasady-ochrany-osobnich-udaju", title: "Zásady ochrany osobních údajů", versions: [{ v: "1.0", from: "2026-11-27" }, { v: "1.1", from: "2026-11-27" }] },
  cookies: { file: "zasady-cookies", title: "Zásady cookies", versions: [{ v: "1.0", from: "2026-11-27" }, { v: "1.1", from: "2026-11-27" }] },
};

const out = {};
for (const [slug, d] of Object.entries(DOCS)) {
  out[slug] = {
    title: d.title,
    versions: d.versions.map(({ v, from }) => ({ v, from, html: readFileSync(`pravni/archiv/${d.file}/${v}.html`, "utf8") })),
  };
}
writeFileSync(
  "src/content/legal.generated.ts",
  `// Generated by scripts/build-legal.mjs – do not edit by hand.\nexport const LEGAL = ${JSON.stringify(out, null, 2)} as const;\n`,
);
console.log("legal docs:", Object.keys(out).join(", "));
